"""Bounded independent regrading of the eight retained November 7 smoke artifacts.

No model calls, source rewriting, original-result writes, or arbitrary restore paths.
Run only after reviewing the original private root and this script's guards.
"""

from __future__ import annotations

import hashlib
import json
import re
import shlex
import shutil
import socket
import stat
import subprocess
import sys
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
import auth_eval
import core_eval
from auth_eval import EvalError

RUNNER_COMMIT = "6036df67f750a4fdd01eae82898ae0ec6f303827"
RUNNER_FILES = {
    "runner_sha256": "tools/core_eval.py",
    "auth_runner_sha256": "tools/auth_eval.py",
    "tasks_sha256": "evals/core/tasks.json",
}
ROOT_PATTERN = r"[^\s\"'<>]*?/feature-auth-eval-[a-z0-9_]{8}(?=/snapshot(?:/|\b))"
FIXTURE_PATTERN = r"\.core-membership-[a-f0-9]{24}\.json"


def selected_files(directory, fixtures=()):
    """Hash generated bytes separately: the reference fingerprint excludes them."""
    values = {}
    for path in directory.rglob("*"):
        relative = path.relative_to(directory)
        if any(part in core_eval.CORE_IGNORED_PARTS for part in relative.parts):
            continue
        if relative.as_posix() in fixtures:
            continue
        if path.is_symlink():
            raise EvalError("replay-generated-symlink")
        if path.is_file():
            values[str(relative)] = hashlib.sha256(path.read_bytes()).hexdigest()
    return values


def proven_root(trace, generated):
    """Bind artifact references to successful actual standalone pwd output."""
    proven = set()
    for line in trace.read_text().splitlines():
        try:
            event = json.loads(line)
        except ValueError:
            continue
        item = event.get("item", {})
        if (
            event.get("type") != "item.completed"
            or item.get("type") != "command_execution"
            or item.get("exit_code") != 0
        ):
            continue
        command = item.get("command", "")
        output = item.get("aggregated_output", "")
        try:
            argv = shlex.split(command)
        except ValueError:
            continue
        payload = argv[-1] if len(argv) >= 3 and argv[-2] in {"-c", "-lc"} else command
        if re.match(r"^\s*pwd\s*(?:$|&&|;|\n)", payload):
            first = next((s.strip() for s in output.splitlines() if s.strip()), "")
            if first.endswith("/snapshot/generated"):
                proven.add(first.removesuffix("/snapshot/generated"))
    references = set()
    for path in generated.rglob("*"):
        if any(
            part in core_eval.CORE_IGNORED_PARTS
            for part in path.relative_to(generated).parts
        ):
            continue
        if path.is_symlink():
            raise EvalError("replay-generated-symlink")
        if path.is_file() and path.stat().st_size <= 2_000_000:
            references.update(re.findall(ROOT_PATTERN, path.read_text(errors="ignore")))
    if len(proven) != 1 or (references and references != proven):
        raise EvalError("replay-workspace-unproven-or-conflicting")
    root = Path(proven.pop())
    if root.parent != Path(tempfile.gettempdir()).resolve() or not re.fullmatch(
        r"feature-auth-eval-[a-z0-9_]{8}", root.name
    ):
        raise EvalError("replay-workspace-outside-owned-temp")
    auth_eval.no_symlink(root)
    if root.exists():
        raise EvalError("replay-workspace-exists")
    return root


def remove_owned_root(root, identity):
    auth_eval.no_symlink(root)
    current = root.stat()
    if (current.st_dev, current.st_ino) != identity:
        raise EvalError("replay-workspace-replaced")
    shutil.rmtree(root)


def unchanged(snapshot, generated_hashes, reference, fixtures=()):
    try:
        return (
            selected_files(snapshot / "generated", fixtures) == generated_hashes
            and auth_eval.fingerprint(snapshot) == reference
        )
    except (OSError, EvalError):
        return False


def files_unchanged(hashes):
    try:
        return all(
            hashlib.sha256(path.read_bytes()).hexdigest() == digest
            for path, digest in hashes.items()
        )
    except OSError:
        return False


def retained_hashes(original, runs):
    values = {}
    for run in runs:
        name = f"{run['stack']}-{run['condition']}-trial-1"
        path = original / name
        values[name] = {
            "result": hashlib.sha256((path / "result.json").read_bytes()).hexdigest(),
            "trace": hashlib.sha256((path / "trace.jsonl").read_bytes()).hexdigest(),
            "reference": auth_eval.digest_hashes(
                auth_eval.fingerprint(path / "snapshot")
            ),
            "generated": auth_eval.digest_hashes(
                selected_files(path / "snapshot/generated")
            ),
        }
    return values


def replay(original, output):
    original = original.resolve()
    output = output.expanduser().absolute()
    auth_eval.no_symlink(output)
    output = output.resolve()
    if output.is_relative_to(original) or original.is_relative_to(output):
        raise EvalError("replay-output-overlaps-original")
    summary_bytes = (original / "summary.json").read_bytes()
    summary = json.loads(summary_bytes)
    if (
        summary.get("total") != 8
        or summary.get("repeats") != 1
        or summary.get("source_commit") != core_eval.SOURCE_COMMIT
    ):
        raise EvalError("replay-not-reviewed-eight-call-smoke")
    pairs = [(run["stack"], run["condition"]) for run in summary["runs"]]
    if len(pairs) != 8 or set(pairs) != {
        (stack, condition)
        for stack in auth_eval.STACKS
        for condition in ("baseline", "catalog")
    }:
        raise EvalError("replay-expected-unique-eight-trials")
    originals_before = retained_hashes(original, summary["runs"])
    for key, name in RUNNER_FILES.items():
        blob = subprocess.check_output(
            ["git", "show", f"{RUNNER_COMMIT}:{name}"], cwd=ROOT
        )
        if hashlib.sha256(blob).hexdigest() != summary[key]:
            raise EvalError("replay-original-runner-mismatch")
    output = auth_eval.prepare_output(output)
    archive, catalog = core_eval.catalog_archive()
    results = []
    with tempfile.TemporaryDirectory(prefix="feature-core-replay-proof-") as temporary:
        template = Path(temporary).resolve() / "source"
        verified = core_eval.freeze_sources(ROOT, template, archive)
        for key, value in {**verified, **catalog}.items():
            if summary.get(key) != value:
                raise EvalError("replay-source-catalog-mismatch")
        reference = auth_eval.fingerprint(template)
        for original_result in summary["runs"]:
            started = time.monotonic()
            name = f"{original_result['stack']}-{original_result['condition']}-trial-1"
            if original_result["stack"] not in auth_eval.STACKS or original_result[
                "condition"
            ] not in {"baseline", "catalog"}:
                raise EvalError("replay-invalid-trial")
            retained = original / name
            result_bytes = (retained / "result.json").read_bytes()
            if json.loads(result_bytes) != original_result:
                raise EvalError("replay-original-result-mismatch")
            trial_output = output / name
            trial_output.mkdir(mode=0o700)
            record = {
                "stack": original_result["stack"],
                "condition": original_result["condition"],
                "original_passed": original_result["passed"],
                "original_error_code": original_result["error_code"],
                "original_result_sha256": hashlib.sha256(result_bytes).hexdigest(),
                "original_agent_seconds": original_result["agent_seconds"],
                "original_elapsed_seconds": original_result["elapsed_seconds"],
                "original_agent": original_result["agent"],
                "trace_sha256": hashlib.sha256(
                    (retained / "trace.jsonl").read_bytes()
                ).hexdigest(),
                "passed": False,
                "checks": [],
                "error_code": None,
            }
            root, identity, current, before = None, None, None, None
            snapshot = retained / "snapshot"
            retained_source = auth_eval.fingerprint(snapshot)
            retained_generated = selected_files(snapshot / "generated")
            try:
                for key in (
                    *RUNNER_FILES,
                    "source_sha256",
                    "catalog_snapshot_sha256",
                    "snapshot_sha256",
                ):
                    expected = (
                        summary["source_sha256"]
                        if key == "snapshot_sha256"
                        else summary[key]
                    )
                    if original_result.get(key) != expected:
                        raise EvalError("replay-trial-provenance-mismatch")
                if auth_eval.fingerprint(snapshot) != reference:
                    raise EvalError("replay-retained-source-mismatch")
                generated = snapshot / "generated"
                fixtures = [
                    path
                    for path in generated.iterdir()
                    if re.fullmatch(FIXTURE_PATTERN, path.name)
                ]
                allowed_failure = (
                    original_result["error_code"] == "generated-source-symlink"
                    and not original_result["passed"]
                )
                if not (original_result["passed"] or allowed_failure) or len(
                    fixtures
                ) != int(original_result["passed"]):
                    raise EvalError("replay-membership-provenance-unavailable")
                for path in fixtures:
                    if (
                        path.is_symlink()
                        or stat.S_IMODE(path.stat().st_mode) != 0o600
                        or not path.is_file()
                    ):
                        raise EvalError("replay-membership-unsafe")
                omitted = {path.name for path in fixtures}
                before = selected_files(generated, omitted)
                record["generated_source_sha256"] = auth_eval.digest_hashes(before)
                root = proven_root(retained / "trace.jsonl", generated)
                root.mkdir(mode=0o700)
                owner = root.stat()
                identity = (owner.st_dev, owner.st_ino)
                work = root / "snapshot"
                shutil.copytree(
                    snapshot,
                    work,
                    symlinks=True,
                    ignore=shutil.ignore_patterns(*core_eval.CORE_IGNORED_PARTS),
                )
                current = work / "generated"
                if (
                    selected_files(current, omitted) != before
                    or auth_eval.fingerprint(work) != reference
                ):
                    raise EvalError("replay-copy-byte-mismatch")
                core_eval.core_reuse_check(
                    current,
                    original_result["stack"],
                    reference,
                    core_eval.SOURCE_COMMIT,
                )
                with socket.socket() as sock:
                    sock.bind(("127.0.0.1", 0))
                    port = sock.getsockname()[1]
                origin = f"http://127.0.0.1:{port}"
                env = auth_eval.environment(port, origin)
                fixture = core_eval.create_membership_file(current, env)
                omitted.add(fixture.name)
                record["checks"] = auth_eval.grade(
                    current,
                    trial_output,
                    env,
                    port,
                    origin,
                    time.monotonic() + 600,
                    http_grader=lambda p, o, d, fixture=fixture: (
                        core_eval.core_http_grade(p, o, d, fixture)
                    ),
                )
                record["passed"] = True
            except (EvalError, OSError, ValueError, subprocess.SubprocessError) as exc:
                record["passed"] = False
                record["error_code"] = (
                    str(exc) if isinstance(exc, EvalError) else "replay-runtime-error"
                )
            finally:
                if current is not None:
                    intact = unchanged(work, before, reference, omitted)
                    record["source_unchanged"] = intact
                    if not intact:
                        record["passed"] = False
                        record["grading_error_code"] = record["error_code"]
                        record["error_code"] = "replay-program-or-source-changed"
                        record["invariance_error_code"] = (
                            "replay-program-or-source-changed"
                        )
                retained_unchanged = files_unchanged(
                    {
                        retained / "result.json": record["original_result_sha256"],
                        retained / "trace.jsonl": record["trace_sha256"],
                    }
                ) and unchanged(snapshot, retained_generated, retained_source)
                record["retained_unchanged"] = retained_unchanged
                if not retained_unchanged:
                    record["passed"] = False
                    record["error_code"] = "replay-retained-artifacts-changed"
                    record["invariance_error_code"] = (
                        "replay-retained-artifacts-changed"
                    )
                if identity:
                    remove_owned_root(root, identity)
                record["replay_seconds"] = round(time.monotonic() - started, 3)
                auth_eval.write_json(trial_output / "replay.json", record)
            results.append(record)
            print(
                name, "PASS" if record["passed"] else record["error_code"], flush=True
            )
    if (original / "summary.json").read_bytes() != summary_bytes:
        raise EvalError("replay-original-summary-changed")
    originals_after = retained_hashes(original, summary["runs"])
    if originals_before != originals_after:
        raise EvalError("replay-original-artifacts-changed")
    report = {
        "suite": "core-catalog-retained-replay-v1",
        "model_calls": 0,
        "originals_unchanged": True,
        "original_artifacts_sha256": auth_eval.digest_hashes(
            {
                name: json.dumps(value, sort_keys=True)
                for name, value in originals_before.items()
            }
        ),
        "original_runner_source_commit": RUNNER_COMMIT,
        "original_summary_sha256": hashlib.sha256(summary_bytes).hexdigest(),
        "replay_helper_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "corrected_runner_sha256": hashlib.sha256(
            Path(core_eval.__file__).read_bytes()
        ).hexdigest(),
        "corrected_auth_runner_sha256": hashlib.sha256(
            Path(auth_eval.__file__).read_bytes()
        ).hexdigest(),
        "source_sha256": summary["source_sha256"],
        "catalog_sha256": summary["catalog_sha256"],
        "passed": sum(record["passed"] for record in results),
        "total": len(results),
        "runs": results,
    }
    auth_eval.write_json(output / "summary.json", report)
    return report


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(
            "Expected original private smoke root and fresh private replay output"
        )
    replay(Path(sys.argv[1]), Path(sys.argv[2]))
